import { getGitHubClient } from "./client";
import { GroundedReviewComment } from "../types/review";
import { DiffSide } from "../types/diff";

export interface SubmitReviewParams {
  owner: string;
  repo: string;
  pullNumber: number;
  commitId: string;
  body: string;
  event: "APPROVE" | "REQUEST_CHANGES" | "COMMENT";
  comments: GroundedReviewComment[];
  userToken?: string;
}

export interface SubmitReviewResult {
  reviewId: number;
  htmlUrl: string;
  state: string;
  commentsCount: number;
  selfApprovalDegraded: boolean;
  degradeNotice?: string;
}

/**
 * Formats a single review comment for GitHub API.
 */
export function formatGitHubCommentBody(comment: GroundedReviewComment): string {
  let md = `**[${comment.severity}]** ${comment.body}\n`;

  if (comment.isSnapped && comment.snapReason) {
    md += `\n> ℹ️ *Diff Grounding: ${comment.snapReason}*\n`;
  }

  if (comment.suggestedChange) {
    md += `\n\`\`\`suggestion\n${comment.suggestedChange}\n\`\`\`\n`;
  }

  return md.trim();
}

/**
 * Prepares the overall review body and groups comments into:
 * - inline comments (EXACT and SNAPPED that have a valid line and file)
 * - file-level comments
 * - general review notes
 */
export function prepareReviewPayload(
  rawBody: string,
  comments: GroundedReviewComment[],
  isSelfApproval: boolean
) {
  let finalBody = rawBody.trim() || "Spoken code review generated by Vox PR.";

  if (isSelfApproval) {
    finalBody = `> ℹ️ **Notice:** Review submitted as *Comment* because GitHub does not permit PR authors to approve their own pull requests.\n\n${finalBody}`;
  }

  const inlineComments: {
    path: string;
    line: number;
    side: DiffSide;
    body: string;
  }[] = [];

  const fileLevelNotes: string[] = [];
  const additionalNotes: string[] = [];

  for (const c of comments) {
    if (c.degradationStatus === "EXACT" || (c.degradationStatus === "SNAPPED" && c.line !== null)) {
      inlineComments.push({
        path: c.path,
        line: c.line!,
        side: c.side || "RIGHT",
        body: formatGitHubCommentBody(c)
      });
    } else if (c.degradationStatus === "FILE_LEVEL") {
      fileLevelNotes.push(
        `#### File: \`${c.path}\`\n**[${c.severity}]** ${c.body}${
          c.suggestedChange ? `\n\n\`\`\`suggestion\n${c.suggestedChange}\n\`\`\`` : ""
        }`
      );
    } else {
      // REVIEW_BODY
      additionalNotes.push(
        `- **[${c.severity}]** (${c.path}): ${c.body}${
          c.suggestedChange ? ` (Suggested change: \`${c.suggestedChange}\`)` : ""
        }`
      );
    }
  }

  if (fileLevelNotes.length > 0) {
    finalBody += `\n\n### File-Level Comments\n${fileLevelNotes.join("\n\n")}`;
  }

  if (additionalNotes.length > 0) {
    finalBody += `\n\n### Additional Review Notes\n${additionalNotes.join("\n")}`;
  }

  return {
    finalBody,
    inlineComments
  };
}

/**
 * Posts a review to GitHub pull requests via Octokit.
 * Handles self-approval detection and degrades event to COMMENT.
 */
export async function submitPullRequestReview(
  params: SubmitReviewParams
): Promise<SubmitReviewResult> {
  const octokit = getGitHubClient(params.userToken);

  // 1. Fetch PR details to verify author for self-approval check
  const prRes = await octokit.rest.pulls.get({
    owner: params.owner,
    repo: params.repo,
    pull_number: params.pullNumber
  });
  const prAuthor = prRes.data.user?.login;

  // 2. Determine who the authenticated reviewer is
  let reviewerLogin: string | null = null;
  try {
    const userRes = await octokit.rest.users.getAuthenticated();
    reviewerLogin = userRes.data.login;
  } catch (e) {
    // Unauthenticated or scoped token where user endpoint is restricted
  }

  // 3. Self-Approval Detection
  let effectiveEvent = params.event;
  let selfApprovalDegraded = false;
  let degradeNotice: string | undefined = undefined;

  if (params.event === "APPROVE" && reviewerLogin && prAuthor && reviewerLogin.toLowerCase() === prAuthor.toLowerCase()) {
    effectiveEvent = "COMMENT";
    selfApprovalDegraded = true;
    degradeNotice = "Degraded from APPROVE to COMMENT because GitHub does not permit author self-approval.";
  }

  // 4. Prepare review body and inline comments
  const { finalBody, inlineComments } = prepareReviewPayload(
    params.body,
    params.comments,
    selfApprovalDegraded
  );

  // 5. Submit review to GitHub API
  const reviewResponse = await octokit.rest.pulls.createReview({
    owner: params.owner,
    repo: params.repo,
    pull_number: params.pullNumber,
    commit_id: params.commitId,
    event: effectiveEvent,
    body: finalBody,
    comments: inlineComments.map((c) => ({
      path: c.path,
      line: c.line,
      side: c.side,
      body: c.body
    }))
  });

  return {
    reviewId: reviewResponse.data.id,
    htmlUrl: reviewResponse.data.html_url,
    state: reviewResponse.data.state,
    commentsCount: inlineComments.length,
    selfApprovalDegraded,
    degradeNotice
  };
}
